import { expect, test, type Page } from '@playwright/test'

async function coords(page: Page) {
  const label = await page.getByTestId('coordinates').textContent()
  return { x: Number(label?.match(/X (-?\d+\.\d+)/)?.[1]), z: Number(label?.match(/Z (-?\d+\.\d+)/)?.[1]) }
}

async function walkToBoard(page: Page) {
  await page.evaluate(() => (document.activeElement as HTMLElement)?.blur())
  await page.keyboard.down('d')
  await expect.poll(async () => (await coords(page)).x, { timeout: 18_000 }).toBeGreaterThan(15)
  await page.keyboard.up('d')
  for (let i = 0; i < 45; i++) {
    const difference = 15.5 - (await coords(page)).x
    if (Math.abs(difference) < 0.55) break
    await page.keyboard.press(difference > 0 ? 'd' : 'a', { delay: Math.min(130, Math.max(40, Math.abs(difference) * 45)) })
    await page.waitForTimeout(60)
  }
  expect(Math.abs(15.5 - (await coords(page)).x)).toBeLessThan(0.9)
  await page.keyboard.down('w')
  await expect(page.getByRole('button', { name: /Board the Ferris wheel/ })).toBeVisible({ timeout: 12_000 })
  await page.keyboard.up('w')
}

test('wheel rotates, boards, follows a cabin, exits safely and can be ridden again', async ({ page }) => {
  test.setTimeout(210_000)
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  await page.getByRole('button', { name: /Enter Silently/i }).click()
  const canvas = page.locator('canvas')
  await expect(canvas).toBeVisible({ timeout: 20_000 })
  await page.getByLabel('Graphics').selectOption('low')
  await expect.poll(() => canvas.getAttribute('data-wheel-angle'), { timeout: 20_000 }).not.toBeNull()
  const angle = Number(await canvas.getAttribute('data-wheel-angle'))
  await expect.poll(async () => Number(await canvas.getAttribute('data-wheel-angle'))).toBeGreaterThan(angle + 0.08)
  await walkToBoard(page)
  await page.screenshot({ path: 'test-results/wheel-desktop-boarding.png' })
  await page.keyboard.press('e')
  await expect(page.getByTestId('ride-state')).toHaveAttribute('data-phase', 'riding', { timeout: 8_000 })
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('banaras-kashi-journey') || '{}').completed)).toContain('wheel')
  const rideStartAngle = Number(await canvas.getAttribute('data-wheel-angle'))
  const frozen = await canvas.getAttribute('data-player-ground')
  await page.keyboard.down('a')
  const firstHeight = Number(await page.getByTestId('ride-height').textContent())
  const firstCamera = await canvas.getAttribute('data-ride-camera')
  const firstGondola = await canvas.getAttribute('data-gondola')
  await expect.poll(async () => Number(await page.getByTestId('ride-height').textContent()), { timeout: 10_000 }).toBeGreaterThan(firstHeight + 0.3)
  await expect.poll(() => canvas.getAttribute('data-ride-camera')).not.toBe(firstCamera)
  await expect.poll(() => canvas.getAttribute('data-gondola')).not.toBe(firstGondola)
  const cameraXYZ = (await canvas.getAttribute('data-ride-camera'))!.split(',').map(Number)
  const cabinXYZ = (await canvas.getAttribute('data-gondola'))!.split(',').map(Number)
  expect(Math.abs(cameraXYZ[1] - cabinXYZ[1])).toBeLessThan(2)
  expect(cameraXYZ[2]).toBeGreaterThan(7)
  await page.keyboard.up('a')
  expect(await canvas.getAttribute('data-player-ground')).toBe(frozen)
  await page.screenshot({ path: 'test-results/wheel-desktop-riding.png' })
  await expect.poll(async () => Number(await page.getByTestId('ride-height').textContent()), { timeout: 18_000 }).toBeGreaterThan(6)
  await page.screenshot({ path: 'test-results/wheel-desktop-elevated.png' })
  await expect.poll(async () => Number(await page.getByTestId('ride-height').textContent()), { timeout: 18_000 }).toBeGreaterThan(11)
  await page.screenshot({ path: 'test-results/wheel-desktop-top.png' })
  await expect.poll(async () => Number(await canvas.getAttribute('data-wheel-angle')) - rideStartAngle, { timeout: 45_000 }).toBeGreaterThan(2 * Math.PI - 0.1)
  expect(Number(await page.getByTestId('ride-height').textContent())).toBeLessThan(3.5)
  expect(Number((await canvas.getAttribute('data-ride-camera'))!.split(',')[2])).toBeGreaterThan(7)
  await page.keyboard.press('e')
  await expect(page.getByTestId('ride-state')).toHaveAttribute('data-phase', 'exiting')
  await expect(page.getByRole('button', { name: /Board the Ferris wheel/ })).toBeVisible({ timeout: 35_000 })
  await expect.poll(async () => Math.abs((await coords(page)).x - 15.5)).toBeLessThan(0.2)
  await expect.poll(async () => Math.abs((await coords(page)).z - 8.6)).toBeLessThan(0.2)
  const returned = await coords(page)
  expect(returned.x).toBeCloseTo(15.5, 0)
  expect(returned.z).toBeCloseTo(8.6, 0)
  await page.getByRole('button', { name: /Board the Ferris wheel/ }).click()
  await expect(page.getByTestId('ride-state')).toHaveAttribute('data-phase', 'riding', { timeout: 8_000 })
  await page.getByRole('button', { name: /Exit ride/ }).click()
  await expect(page.getByRole('button', { name: /Board the Ferris wheel/ })).toBeVisible({ timeout: 35_000 })
  await page.keyboard.down('a')
  await expect.poll(async () => (await coords(page)).x).toBeLessThan(15)
  await page.keyboard.up('a')
  await page.mouse.move(450, 320)
  await page.mouse.down()
  await page.mouse.move(520, 320, { steps: 8 })
  await page.mouse.up()
  await expect.poll(() => page.getByTestId('coordinates').textContent()).not.toContain('· 0°')
  expect(errors).toEqual([])
})

test('a touch visitor can approach, board and exit at 390 × 844', async ({ browser }) => {
  test.setTimeout(90_000)
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 })
  const page = await context.newPage()
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  await page.getByRole('button', { name: /Enter Silently/i }).click()
  const joystick = page.getByRole('group', { name: 'Movement joystick' })
  const box = await joystick.boundingBox()
  expect(box).not.toBeNull()
  const x = box!.x + box!.width / 2, y = box!.y + box!.height / 2
  const cdp = await context.newCDPSession(page)
  async function push(dx: number, dy: number, predicate: () => Promise<boolean>) {
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y, id: 1 }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + dx, y: y + dy, id: 1 }] })
    await expect.poll(predicate, { timeout: 18_000 }).toBe(true)
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  }
  await push(40, 0, async () => (await coords(page)).x > 15)
  for (let attempt = 0; attempt < 14; attempt++) {
    const difference = 15.5 - (await coords(page)).x
    if (Math.abs(difference) < 0.65) break
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y, id: 1 }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + Math.sign(difference) * 40, y, id: 1 }] })
    await page.waitForTimeout(Math.min(350, Math.max(100, Math.abs(difference) * 75)))
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await page.waitForTimeout(110)
  }
  expect(Math.abs(15.5 - (await coords(page)).x)).toBeLessThan(1)
  await push(0, -40, async () => await page.getByRole('button', { name: /Board the Ferris wheel/ }).isVisible())
  await page.screenshot({ path: 'test-results/wheel-mobile-boarding.png' })
  await page.getByRole('button', { name: /Board the Ferris wheel/ }).click()
  await expect(page.getByTestId('ride-state')).toHaveAttribute('data-phase', 'riding', { timeout: 8_000 })
  await expect(joystick).not.toBeVisible()
  await page.screenshot({ path: 'test-results/wheel-mobile-riding.png' })
  await expect.poll(async () => Number(await page.getByTestId('ride-height').textContent()), { timeout: 18_000 }).toBeGreaterThan(6)
  await page.screenshot({ path: 'test-results/wheel-mobile-elevated.png' })
  await expect.poll(async () => Number(await page.getByTestId('ride-height').textContent()), { timeout: 18_000 }).toBeGreaterThan(11)
  await page.screenshot({ path: 'test-results/wheel-mobile-top.png' })
  await page.getByLabel('Graphics').selectOption('high')
  await expect(page.locator('canvas')).toBeVisible()
  await page.screenshot({ path: 'test-results/wheel-mobile-high.png' })
  await page.getByLabel('Graphics').selectOption('low')
  await page.getByRole('button', { name: /Exit ride/ }).click()
  await expect(joystick).toBeVisible({ timeout: 18_000 })
  await expect(page.getByRole('button', { name: /Board the Ferris wheel/ })).toBeVisible()
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 250, y: 390, id: 2 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 310, y: 390, id: 2 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect.poll(() => page.getByTestId('coordinates').textContent()).not.toContain('· 0°')
  expect(errors).toEqual([])
  await context.close()
})
