import { expect, test } from '@playwright/test'
import { mkdirSync } from 'node:fs'
const shots = 'test-results/phase4b'
mkdirSync(shots, { recursive: true })

test('fireworks repeat and toggle without removing the running world', async ({ page }) => {
  test.setTimeout(70_000)
  await page.goto('/')
  await page.getByRole('button', { name: /Enter Silently/i }).click()
  const canvas = page.locator('canvas')
  await expect.poll(() => canvas.getAttribute('data-fireworks'), { timeout: 45_000, intervals: [100] }).toMatch(/colour:[1-5]\./)
  const first = await canvas.getAttribute('data-fireworks')
  await expect.poll(() => canvas.getAttribute('data-fireworks')).not.toBe(first)
  await page.screenshot({ path: `${shots}/desktop-fireworks.png` })
  await page.getByRole('button', { name: 'Fireworks: On' }).click()
  await expect(page.getByRole('button', { name: 'Fireworks: Off' })).toHaveAttribute('aria-pressed', 'false')
  await expect(canvas).toHaveAttribute('data-fireworks', 'off')
  await expect(canvas).toBeVisible()
})

test('pendulum can board, swing, exit and reset safely', async ({ page }) => {
  test.setTimeout(120_000)
  await page.goto('/')
  await page.getByRole('button', { name: /Enter Silently/i }).click()
  await page.getByLabel('Graphics').selectOption('low')
  for (let i = 0; i < 10 && Number((await page.getByTestId('coordinates').textContent())?.match(/Z (-?\d+\.\d+)/)?.[1]) > 9.5; i++) await page.keyboard.press('w', { delay: 150 })
  await expect.poll(async () => Number((await page.getByTestId('coordinates').textContent())?.match(/Z (-?\d+\.\d+)/)?.[1])).toBeLessThan(9.6)
  await page.keyboard.down('a')
  await expect.poll(() => page.getByRole('button', { name: /Board the pendulum/i }).count(), { timeout: 30000, intervals: [50] }).toBe(1)
  await page.keyboard.up('a')
  await expect(page.getByRole('button', { name: /Board the pendulum/i })).toBeVisible()
  await page.screenshot({ path: `${shots}/pendulum-rest.png` })
  await page.getByRole('button', { name: /Board the pendulum/i }).click()
  await expect(page.getByTestId('ride-state')).toHaveAttribute('data-phase', 'riding', { timeout: 15000 })
  const angle = await page.locator('canvas').getAttribute('data-pendulum-angle')
  await expect.poll(() => page.locator('canvas').getAttribute('data-pendulum-angle')).not.toBe(angle)
  await page.screenshot({ path: `${shots}/pendulum-riding.png` })
  await page.waitForTimeout(750)
  await page.screenshot({ path: `${shots}/pendulum-motion.png` })
  await page.getByRole('button', { name: /Exit ride/i }).click()
  await expect(page.getByTestId('coordinates')).toContainText('X -16.5', { timeout: 15000 })
  await page.getByRole('button', { name: 'Reset' }).click()
  await expect(page.getByTestId('coordinates')).toContainText('X 0.0', { timeout: 15000 })
})

test('ferry and cruise follow distinct water routes, return player safely', async ({ page }) => {
  test.setTimeout(180_000)
  await page.goto('/')
  await page.getByRole('button', { name: /Enter Silently/i }).click()
  await page.getByLabel('Graphics').selectOption('low')
  await page.keyboard.down('w')
  await expect.poll(async () => Number((await page.getByTestId('coordinates').textContent())?.match(/Z (-?\d+\.\d+)/)?.[1]), { timeout: 35_000, intervals: [100] }).toBeLessThan(2)
  await page.keyboard.up('w')
  async function approachDock(x: number, label: RegExp) {
    const prompt = page.getByRole('button', { name: label })
    for (let attempt = 0; attempt < 60 && !await prompt.isVisible(); attempt++) {
      const current = Number((await page.getByTestId('coordinates').textContent())?.match(/X (-?\d+\.\d+)/)?.[1])
      await page.keyboard.press(current > x ? 'a' : 'd', { delay: 130 })
    }
    await expect(prompt).toBeVisible()
    return prompt
  }
  await (await approachDock(4, /Board the Ferry/i)).click()
  await expect(page.getByTestId('ride-state')).toHaveAttribute('data-phase', 'riding', { timeout: 15000 })
  const before = await page.locator('canvas').getAttribute('data-ferry-position')
  await expect.poll(() => page.locator('canvas').getAttribute('data-ferry-position')).not.toBe(before)
  await page.screenshot({ path: `${shots}/ferry-in-motion.png` })
  await page.getByRole('button', { name: /Exit ride/i }).click()
  await expect(page.getByTestId('coordinates')).toContainText('X 4.0', { timeout: 15000 })
  await (await approachDock(17, /Board the Ganga cruise/i)).click()
  await expect(page.getByTestId('ride-state')).toHaveAttribute('data-phase', 'riding', { timeout: 15000 })
  const cruiseBefore = await page.locator('canvas').getAttribute('data-cruise-position')
  await expect.poll(() => page.locator('canvas').getAttribute('data-cruise-position')).not.toBe(cruiseBefore)
  await page.screenshot({ path: `${shots}/cruise-view.png` })
  await page.getByRole('button', { name: /Exit ride/i }).click()
  await expect(page.getByTestId('coordinates')).toContainText('X 17.0', { timeout: 15000 })
})

