import { expect, test } from '@playwright/test'

test('scene starts, responds to controls and changes graphics settings', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: /Enter Silently/i }).click()
  const canvas = page.locator('canvas')
  await expect(canvas).toBeVisible({ timeout: 20_000 })
  await page.waitForTimeout(800)
  await page.screenshot({ path: 'test-results/scene-desktop-high.png' })
  const high = await canvas.evaluate((element) => element.width / element.clientWidth)
  expect(high).toBeGreaterThan(1.5)
  await page.getByLabel('Graphics').selectOption('low')
  await expect.poll(() => canvas.evaluate((element) => element.width / element.clientWidth)).toBeLessThan(high)
  await page.keyboard.down('w')
  await expect.poll(async () => Number((await page.getByTestId('coordinates').textContent())?.match(/Z (\d+\.\d+)/)?.[1]), { timeout: 15_000 }).toBeLessThan(10.5)
  await page.keyboard.up('w')
  const box = await canvas.boundingBox()
  expect(box).not.toBeNull()
  await page.mouse.move(box!.x + 500, box!.y + 350)
  await page.mouse.down()
  await page.mouse.move(box!.x + 600, box!.y + 380, { steps: 10 })
  await page.mouse.up()
  await expect.poll(() => page.getByTestId('coordinates').textContent()).not.toContain('· 0°')
  await page.keyboard.down('w')
  await expect.poll(async () => Number((await page.getByTestId('coordinates').textContent())?.match(/Z (\d+\.\d+)/)?.[1]), { timeout: 20_000 }).toBeLessThanOrEqual(1)
  await page.keyboard.up('w')
  const z = Number((await page.getByTestId('coordinates').textContent())?.match(/Z (\d+\.\d+)/)?.[1])
  expect(z).toBeGreaterThanOrEqual(0.7)
  expect(z).toBeLessThanOrEqual(1)
  await page.getByRole('button', { name: 'Reset' }).click()
  await page.setViewportSize({ width: 800, height: 540 })
  await expect(canvas).toBeVisible()
  expect(errors).toEqual([])
  await page.screenshot({ path: 'test-results/desktop-world.png' })
})

test('touch joystick and camera drag are available on small screens', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 2 })
  const page = await context.newPage()
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: /Enter Silently/i }).click()
  const stick = page.locator('.stick')
  const joystick = page.getByRole('group', { name: 'Movement joystick' })
  await expect(joystick).toBeVisible()
  const box = await joystick.boundingBox()
  expect(box).not.toBeNull()
  const x = box!.x + 55, y = box!.y + 55
  await joystick.evaluate((element) => {
    element.addEventListener('gotpointercapture', () => { element.dataset.captured = 'true' }, { once: true })
  })
  const cdp = await context.newCDPSession(page)
  const stickTouch = { x, y, id: 1 }
  const movedStick = { x: x + 30, y: y - 20, id: 1 }
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [stickTouch] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [movedStick] })
  await expect(joystick).toHaveAttribute('data-captured', 'true')
  await expect(stick).not.toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
  await expect.poll(async () => Number((await page.getByTestId('coordinates').textContent())?.match(/X (-?\d+\.\d+)/)?.[1])).toBeGreaterThan(0)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [movedStick, { x: 200, y: 380, id: 2 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [movedStick, { x: 260, y: 380, id: 2 }] })
  await expect.poll(() => page.getByTestId('coordinates').textContent()).not.toContain('· 0°')
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [movedStick] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(stick).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
  await page.getByRole('button', { name: 'Reset' }).click()
  await expect(page.locator('canvas')).toBeVisible()
  await page.setViewportSize({ width: 844, height: 390 })
  await expect(joystick).toBeVisible()
  await expect(page.locator('canvas')).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForTimeout(1200)
  expect(errors).toEqual([])
  await page.screenshot({ path: 'test-results/mobile-world.png' })
  await context.close()
})
