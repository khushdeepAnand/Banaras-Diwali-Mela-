import { expect, test } from '@playwright/test'
import { mkdirSync } from 'node:fs'
const shots = 'test-results/phase5'
mkdirSync(shots, { recursive: true })
const adminToken = 'playwright-local-only-admin-token-1234567890'

test('welcome, amount selection, demo submission and explicit manual-review result', async ({ page }) => {
  await page.goto('/')
  await page.screenshot({ path: `${shots}/welcome.png` })
  await page.getByRole('button', { name: /Contribute ₹21/i }).click()
  await expect(page.getByText(/LOCAL DEMO ONLY/)).toBeVisible()
  await page.getByRole('group', { name: 'Contribution amount' }).getByRole('button', { name: '₹51' }).click()
  await expect(page.locator('.payment-summary')).toContainText('₹51 · DEMO · no payment')
  await expect(page.locator('.payment-summary img')).toHaveCount(0)
  await page.screenshot({ path: `${shots}/contribution.png` })
  await page.getByPlaceholder('From your UPI app').fill(`UTRDEMO${Date.now()}`)
  await page.getByRole('button', { name: /Submit reference for manual verification/i }).click()
  await expect(page.getByRole('status').filter({ hasText: /NOT proof of payment/i })).toBeVisible()
  await expect(page.locator('.result-reference')).toContainText('pending_verification')
  await expect(page.locator('.result-reference')).toContainText('TEMPORARY DEMO')
  await page.screenshot({ path: `${shots}/contribution-pending.png` })
})

test('vendor application, protected organiser actions and approved kiosk publication', async ({ page, request }) => {
  test.setTimeout(100_000)
  const vendor = `Weave Studio ${Date.now()}`
  await page.goto('/')
  await page.getByRole('button', { name: 'Apply for a stall' }).click()
  await expect(page.getByText(/LOCAL DEMO ONLY/)).toBeVisible()
  await page.getByRole('textbox', { name: 'Stall name' }).fill(vendor)
  await page.getByRole('textbox', { name: 'Vendor name' }).fill('Asha Kumar')
  await page.getByRole('textbox', { name: 'Email' }).first().fill('asha@example.test')
  await page.getByRole('textbox', { name: 'Phone' }).fill('+919123456789')
  await page.getByRole('textbox', { name: 'Category' }).fill('Textiles')
  await page.getByRole('textbox', { name: 'Short description' }).fill('Handwoven colourful textiles and scarves from local craftspeople.')
  await page.getByRole('textbox', { name: /Optional products/ }).fill('Silk scarf\nCotton shawl')
  await page.screenshot({ path: `${shots}/vendor-application.png` })
  await page.getByRole('button', { name: 'Submit stall application' }).click()
  await expect(page.locator('.result-reference')).toContainText('pending_payment')
  const reference = (await page.locator('.result-reference').textContent())!.match(/BDMS-[A-Z0-9]+/)![0]
  await page.locator('input[name="stallUtr"]').fill(`VENDORREF${Date.now()}`)
  await page.getByRole('button', { name: /Submit UTR for manual review/i }).click()
  await expect(page.locator('.result-reference')).toContainText('pending_verification')
  const unauthorised = await request.patch(`http://127.0.0.1:3101/api/admin/applications/${reference}`, { data: { status: 'approved' } })
  expect(unauthorised.status()).toBe(401)
  await page.getByRole('button', { name: 'Close' }).click()
  await page.getByRole('button', { name: 'Organiser access' }).click()
  await page.getByLabel('Organiser API token').fill(adminToken)
  await page.getByRole('button', { name: 'Load protected records' }).click()
  await expect(page.locator('.admin-record').filter({ hasText: vendor })).toBeVisible()
  await page.screenshot({ path: `${shots}/organiser-view.png` })
  const record = page.locator('.admin-record').filter({ hasText: vendor })
  await record.getByRole('button', { name: 'Approve' }).click()
  await record.getByRole('button', { name: 'Mark payment verified' }).click()
  await record.getByRole('button', { name: 'Publish', exact: true }).click()
  const published = await request.get('http://127.0.0.1:3101/api/stalls')
  expect((await published.json()).data.some((item: { reference: string }) => item.reference === reference)).toBe(true)
  await page.getByRole('button', { name: 'Close' }).click()
  await page.getByRole('button', { name: /Enter Silently/i }).click()
  await page.getByLabel('Graphics').selectOption('low')
  await page.keyboard.down('a')
  await expect.poll(async () => Number((await page.getByTestId('coordinates').textContent())?.match(/X (-?\d+\.\d+)/)?.[1]), { timeout: 20000, intervals: [50] }).toBeLessThan(-19)
  await page.keyboard.up('a')
  await page.keyboard.down('s')
  await expect.poll(async () => Number((await page.getByTestId('coordinates').textContent())?.match(/Z (-?\d+\.\d+)/)?.[1]), { timeout: 12000, intervals: [50] }).toBeGreaterThan(13.7)
  await page.keyboard.up('s')
  await expect(page.getByRole('button', { name: new RegExp(vendor) })).toBeVisible()
  await page.screenshot({ path: `${shots}/expanded-market.png` })
  await page.getByRole('button', { name: new RegExp(vendor) }).click()
  await expect(page.getByText(/Published vendor listing/)).toBeVisible()
  await page.getByRole('button', { name: 'Close stall panel' }).click()
  await page.getByRole('button', { name: 'Vendors' }).click()
  await expect(page.getByRole('dialog', { name: 'Published vendor directory' })).toContainText(vendor)
  await page.screenshot({ path: `${shots}/vendor-directory.png` })
})

