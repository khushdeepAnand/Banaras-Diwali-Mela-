test('polished river and fireworks are visible in the running world', async ({ page }) => {
  test.setTimeout(65_000)
  await page.goto('/')
  await page.getByRole('button', { name: /Enter Silently/i }).click()
  await page.getByLabel('Graphics').selectOption('low')
  await expect.poll(() => page.locator('canvas').getAttribute('data-fireworks'), { timeout: 45000, intervals: [100] }).toMatch(/colour:[1-5]\./)
  await page.screenshot({ path: `${shots}/river-fireworks.png` })
  await page.keyboard.down('w')
  await expect.poll(async () => Number((await page.getByTestId('coordinates').textContent())?.match(/Z (-?\d+\.\d+)/)?.[1]), { timeout: 14000, intervals: [100] }).toBeLessThan(3.4)
  await page.keyboard.up('w')
  await page.screenshot({ path: `${shots}/water-close.png` })
})
